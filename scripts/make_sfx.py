"""Synthesises HomaCapture's sound effects and writes them into app/src/video/sfx.ts as data URLs.

Made from numbers, not samples, so they carry no licence and can never trigger a copyright claim. Run again after
changing a recipe:  python3 scripts/make_sfx.py
- whoosh: band-passed noise sweeping up then down (punch-ins, B-roll)
- pop:    a short pitched blip with a soft click on top (text pops)
"""
import base64, io, os, wave
import numpy as np

RATE = 32000
rng = np.random.default_rng(7)

def lowpass(x, cut):
    """One-pole low-pass with a per-sample cutoff (Hz)."""
    y = np.zeros_like(x); a = 1 - np.exp(-2 * np.pi * np.asarray(cut) / RATE); a = np.broadcast_to(a, x.shape); s = 0.0
    for i in range(len(x)): s += a[i] * (x[i] - s); y[i] = s
    return y

def whoosh(d=0.42):
    n = int(RATE * d); t = np.arange(n) / RATE; p = t / d
    noise = rng.standard_normal(n)
    sweep = 500 + 5200 * np.sin(np.pi * np.clip(p / 0.9, 0, 1)) ** 1.6
    band = lowpass(noise, sweep) - lowpass(noise, sweep * 0.25)
    env = np.where(p < 0.62, (p / 0.62) ** 2.2, np.exp(-(p - 0.62) * 11))
    return band * env

def pop(d=0.13):
    n = int(RATE * d); t = np.arange(n) / RATE
    f = 360 + 780 * np.exp(-t * 38)
    tone = np.sin(2 * np.pi * np.cumsum(f) / RATE) * np.exp(-t * 34)
    click = lowpass(rng.standard_normal(n), 3000) * np.exp(-t * 400) * 0.6
    return (tone + click) * np.minimum(1, t / 0.002)

def wav_b64(x, peak=0.85):
    x = x / (np.abs(x).max() or 1) * peak
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(RATE); w.writeframes((x * 32767).astype("<i2").tobytes())
    return "data:audio/wav;base64," + base64.b64encode(buf.getvalue()).decode()

out = os.path.join(os.path.dirname(__file__), "..", "app", "src", "video", "sfx.ts")
with open(out, "w") as fh:
    fh.write("/** Generated by scripts/make_sfx.py — synthesised sound effects (no samples, no licence, no copyright claims). */\n")
    fh.write(f"export const WHOOSH = '{wav_b64(whoosh(), 0.7)}'\n")
    fh.write(f"export const POP = '{wav_b64(pop())}'\n")
print("wrote", os.path.normpath(out), os.path.getsize(out), "bytes")
